(function initMethods() {
  const steps = document.querySelectorAll('.method-step');
  const detail = document.getElementById('methodDetail');
  if (!steps.length || !detail) return;

  const DATA = [
    {
      title: '👁 Наблюдение',
      text: 'Мы смотрим на явление и замечаем, что происходит, <b>не вмешиваясь</b> в процесс. Например: ржавеет гвоздь, тает лёд, темнеет чай с лимоном. Наблюдение отвечает на вопрос «что происходит?», но не объясняет «почему?».',
      example: '<b>Пример из химии:</b> мы замечаем, что железный гвоздь со временем покрывается рыхлым рыжим налётом.'
    },
    {
      title: '🧠 Гипотеза',
      text: 'Учёный выдвигает <b>предположение</b>, почему явление происходит именно так. Это ещё не доказанное объяснение, но разумная догадка. Гипотезу можно проверить.',
      example: '<b>Пример из химии:</b> «Возможно, гвоздь ржавеет потому, что в воздухе есть кислород и вода».'
    },
    {
      title: '🧪 Эксперимент',
      text: 'Проверяем гипотезу в контролируемых условиях: смешиваем растворы, нагреваем, охлаждаем, добавляем реагенты. Эксперимент — это <b>активное воздействие</b> на вещество, чтобы увидеть реакцию.',
      example: '<b>Пример из химии:</b> кладём один гвоздь в банку с водой (без воздуха), а другой — во влажный воздух. Смотрим, где появится ржавчина.'
    },
    {
      title: '📏 Измерение',
      text: 'Определяем числовые характеристики: массу, объём, температуру, плотность, кислотность. Без измерений химия не была бы точной наукой — <b>числа превращают догадку в знание</b>.',
      example: '<b>Пример из химии:</b> взвешиваем гвоздь до и после эксперимента и замеряем, сколько ржавчины образовалось.'
    },
    {
      title: '🔮 Модель',
      text: 'Строим <b>упрощённое описание</b> объекта: модель атома, шаростержневую молекулу, компьютерную симуляцию реакции. Модель не заменяет реальность, но помогает её понять и предсказать новые свойства.',
      example: '<b>Пример из химии:</b> рисуем схему, как частицы кислорода соединяются с частицами железа, образуя ржавчину.'
    }
  ];

  function activate(i) {
    steps.forEach((s, idx) => {
      s.classList.toggle('active', idx === i);
    });
    const d = DATA[i];
    detail.innerHTML = `
      <div class="mb-title">${d.title}</div>
      <div class="mb-text">${d.text}</div>
      <div class="mb-text" style="margin-top:10px;padding-top:10px;border-top:1px solid rgba(255,255,255,.15);font-size:14.5px;">${d.example}</div>
    `;
  }

  steps.forEach((step, i) => {
    step.addEventListener('click', () => activate(i));
  });

  activate(0);
})();
